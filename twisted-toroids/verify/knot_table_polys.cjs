// Reads the rows from make_knot_table.py on stdin, adds Jones and Alexander
// polynomials computed by knotmath.js, and prints knot-table.js.
const KM = require('../knotmath.js');
const rows = JSON.parse(require('fs').readFileSync(0, 'utf8'));
for (const r of rows) {
  const j = KM.jones(r.n, r.word, { budget: 1e9 });
  r.jones = [j.o, j.c];
  r.alexander = KM.alexander(r.n, r.word);
  r.linking = KM.readBraid(r.n, r.word).linking;
}
const lines = rows.map(r => '    ' + JSON.stringify(r));
process.stdout.write(`/* Generated by verify/make_knot_table.py from SnapPy's copy of the Rolfsen tables:
   prime knots up to 10 crossings and prime links up to 8 crossings. Each entry has a
   braid word for the knot or link (as SnapPy draws it), its Jones polynomial as
   [lowest power of t^(1/2), coefficients] and its Alexander polynomial, both computed
   from that braid word by knotmath.js. Do not edit by hand. */
(function (root) {
  'use strict';
  const ENTRIES = [
${lines.join(',\n')}
  ];
  if (typeof module !== 'undefined' && module.exports) module.exports = ENTRIES;
  else root.KnotTableEntries = ENTRIES;
})(typeof window !== 'undefined' ? window : globalThis);
`);
